it("requires an explicit accept and never joins locally from an invitation id", async () => {
  const dir = mkdtempSync(join(tmpdir(), "campfire-cli-link-"));
  const runtime = createRuntimeFromPath(join(dir, "owner.db"));
  seedFixture(runtime.store);
  const server = await startCampfireHttpServer({ runtime, port: 0 });
  const humans = runtime.store.countHumans();
  cleanup.push(() => rmSync(dir, { recursive: true, force: true }), () => runtime.close(), () => server.close());
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", join(dir, "owner-profile"));
  vi.stubEnv("CAMPFIRE_DATA_DIR", join(dir, "owner-data"));
  vi.stubEnv("HOME", join(dir, "home"));
  vi.stubEnv("XDG_CONFIG_HOME", join(dir, "xdg"));
  vi.stubEnv("CAMPFIRE_URL", server.url);
  vi.stubEnv("CAMPFIRE_TOKEN", FIXTURE.tokens.sergio);
  const output: string[] = [];
  const errors: string[] = [];
  vi.spyOn(console, "log").mockImplementation((value) => output.push(String(value)));
  vi.spyOn(console, "error").mockImplementation((value) => errors.push(String(value)));
  const file = join(dir, "invite.json");
  expect(await runCliEntry(["invite-teammate", FIXTURE.workspaces.billing, "--out", file, "--allow-loopback", "--output", "json"])).toBe(0);
  const stored = JSON.parse(readFileSync(file, "utf8"));
  const printed = JSON.parse(output.at(-1) ?? "{}") as { link: string; secret?: string };
  expect(printed.link).toContain("/join#v1.");
  expect(printed).not.toHaveProperty("secret");
  expect(output.join("\n")).not.toContain(stored.secret);
  output.length = 0;
  errors.length = 0;
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", join(dir, "recipient"));
  vi.stubEnv("CAMPFIRE_DATA_DIR", join(dir, "recipient-data"));
  vi.stubEnv("CAMPFIRE_URL", "");
  vi.stubEnv("CAMPFIRE_TOKEN", "");
  expect(await runCliEntry(["join", "--invitation-link", printed.link, "--allow-loopback", "--output", "json"])).toBe(0);
  const preview = JSON.parse(output.at(-1) ?? "{}");
  expect(preview).toMatchObject({ status: "pending", inviter: { name: "Sergio" }, workspace: { name: "billing-deploy-failure" } });
  expect(JSON.stringify(preview)).not.toContain(stored.secret);
  expect(existsSync(join(dir, "recipient-data"))).toBe(false);
  expect(runtime.store.countHumans()).toBe(humans);
  output.length = 0;
  expect(await runCliEntry(["join", stored.invitationId, "--output", "json"])).toBe(1);
  expect(errors.join("\n")).toContain("invitation id");
  expect(errors.join("\n")).not.toContain(stored.secret);
  expect(runtime.store.countHumans()).toBe(humans);
  expect(existsSync(join(resolveProfilePaths().configDir, "pending-enrollment.json"))).toBe(false);
  output.length = 0;
  expect(await runCliEntry(["join", "--invitation-link", printed.link, "--decline", "--allow-loopback", "--output", "json"])).toBe(0);
  expect(JSON.parse(output.at(-1) ?? "{}")).toMatchObject({ outcome: "declined", membershipCreated: false });
  expect(runtime.store.countHumans()).toBe(humans);
  expect(runtime.store.getParticipant(FIXTURE.workspaces.billing, { actorId: FIXTURE.humans.sergio, actorType: "human" })?.role).toBe("owner");
  output.length = 0;
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", join(dir, "owner-profile"));
  vi.stubEnv("CAMPFIRE_TOKEN", FIXTURE.tokens.sergio);
  vi.stubEnv("CAMPFIRE_URL", server.url);
  expect(await runCliEntry(["invite-teammate", FIXTURE.workspaces.billing, "--allow-loopback", "--output", "json"])).toBe(0);
  const second = JSON.parse(output.at(-1) ?? "{}") as { link: string };
  expect(second.link).not.toContain(stored.secret);
  output.length = 0;
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", join(dir, "accepted"));
  vi.stubEnv("CAMPFIRE_TOKEN", "");
  vi.stubEnv("CAMPFIRE_URL", "");
  expect(await runCliEntry(["join", "--invitation-link", second.link, "--accept", "--human-name", "Ruth Link", "--harness", "opencode", "--allow-loopback", "--output", "json"])).toBe(0);
  expect(loadRemoteProfile()?.humanName).toBe("Ruth Link");
  expect(loadRemoteProfile()?.workspaceId).toBe(FIXTURE.workspaces.billing);
  expect(loadRemoteProfile()?.agents).toHaveLength(1);
  expect(existsSync(resolveProfilePaths().defaultDatabasePath)).toBe(false);
  expect(runtime.store.countHumans()).toBe(humans + 1);
  const status = output.length;
  expect(await runCliEntry(["status", "--output", "json"])).toBe(0);
  expect(output.slice(status).join("\n")).not.toContain("cfe_");
});
