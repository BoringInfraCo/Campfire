import { afterEach, expect, it, vi } from "vitest";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { delimiter, join } from "node:path";
import { tmpdir } from "node:os";
import { parse as parseJsonc } from "jsonc-parser";
import { runCliEntry } from "../../src/cli/index.js";
import { createRuntimeFromPath } from "../../src/runtime.js";
import { FIXTURE, seedFixture } from "../../src/bootstrap/seed.js";
import { startCampfireHttpServer } from "../../src/http/server.js";
import { loadAnyProfile, loadCredentials, resolveProfilePaths } from "../../src/bootstrap/profile.js";
import { campfireHttpCall } from "../../src/http/client.js";
import { formatInvitationLink } from "../../src/bootstrap/invitation-link.js";
import type { IssuedEnrollmentInvitation } from "../../src/domain/enrollment.js";

const cleanup: Array<() => void | Promise<void>> = [];
afterEach(async () => { for (const close of cleanup.reverse()) await close(); cleanup.length = 0; vi.unstubAllEnvs(); vi.unstubAllGlobals(); vi.restoreAllMocks(); });

for (const major of [1, 2] as const) it(`joins an existing user safely with OpenCode ${major}, retries, and switches profiles`, async () => {
  const dir = mkdtempSync(join(tmpdir(), "campfire-existing-join-"));
  const runtime = createRuntimeFromPath(join(dir, "owner.db")); seedFixture(runtime.store);
  const server = await startCampfireHttpServer({ runtime, port: 0 });
  cleanup.push(() => rmSync(dir, { recursive: true, force: true }), () => runtime.close(), () => server.close());
  const home = join(dir, "home"), xdg = join(dir, "xdg"), bin = join(dir, "bin"), root = join(dir, "profile");
  mkdirSync(bin, { recursive: true });
  const executable = join(bin, "opencode"); writeFileSync(executable, `#!/bin/sh\nif [ "$1" = "--version" ]; then printf '${major}.3.0\\n'; elif [ '${major}' = 1 ]; then if [ -f "$XDG_CONFIG_HOME/opencode/opencode.json" ]; then cat "$XDG_CONFIG_HOME/opencode/opencode.json"; else printf '{}'; fi; elif [ -f "$XDG_CONFIG_HOME/opencode/opencode.json" ]; then printf '[{"type":"document","path":"%s/opencode/opencode.json","info":' "$XDG_CONFIG_HOME"; cat "$XDG_CONFIG_HOME/opencode/opencode.json"; printf '}]'; else printf '[]'; fi\n`); chmodSync(executable, 0o755);
  vi.stubEnv("PATH", `${bin}${delimiter}${process.env.PATH ?? ""}`);
  vi.stubEnv("HOME", home); vi.stubEnv("XDG_CONFIG_HOME", xdg); vi.stubEnv("CAMPFIRE_DATA_DIR", join(dir, "data"));
  for (const key of ["CAMPFIRE_ACTOR_ID", "CAMPFIRE_ACTOR_TYPE", "CAMPFIRE_SESSION_ID", "CAMPFIRE_HARNESS"]) vi.stubEnv(key, "");
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", join(dir, "owner")); vi.stubEnv("CAMPFIRE_URL", server.url); vi.stubEnv("CAMPFIRE_TOKEN", FIXTURE.tokens.sergio);
  const output: string[] = [], errors: string[] = [];
  vi.spyOn(console, "log").mockImplementation((value) => output.push(String(value)));
  vi.spyOn(console, "error").mockImplementation((value) => errors.push(String(value)));
  expect(await runCliEntry(["invite-teammate", FIXTURE.workspaces.billing, "--allow-loopback", "--output", "json"])).toBe(0);
  const { link } = JSON.parse(output.at(-1) ?? "{}") as { link: string };

  mkdirSync(root, { recursive: true, mode: 0o700 });
  const oldProfile = JSON.stringify({ version: 1, databasePath: join(dir, "original.db"), url: "http://127.0.0.1:9414", humanId: "hum_old", humanName: "Old User" });
  const oldCredentials = JSON.stringify({ humanToken: "old-human-token" });
  writeFileSync(join(root, "config.json"), oldProfile); writeFileSync(join(root, "credentials.json"), oldCredentials, { mode: 0o600 });
  const opencodeDir = join(xdg, "opencode");
  mkdirSync(opencodeDir, { recursive: true });
  const configPath = join(opencodeDir, "opencode.json");
  const oldServer = { type: "local", command: ["old-campfire", "mcp"], ...(major === 2 ? { disabled: false } : { enabled: true }), environment: { CAMPFIRE_URL: "https://old.example", CAMPFIRE_TOKEN: "old-agent-token", CAMPFIRE_HARNESS: "opencode" } };
  writeFileSync(configPath, JSON.stringify(major === 2 ? { mcp: { servers: { campfire: oldServer } } } : { mcp: { campfire: oldServer } }));
  vi.stubEnv("CAMPFIRE_CONFIG_DIR", root); vi.stubEnv("CAMPFIRE_URL", ""); vi.stubEnv("CAMPFIRE_TOKEN", "");
  const args = ["join", "--invitation-link", link, "--accept", "--human-name", "Sammi", "--harness", "opencode", "--allow-loopback", "--output", "json"];
  const beforeJoin = runtime.store.countHumans();
  vi.stubEnv("CAMPFIRE_TOKEN", "stale-secret-token");
  expect(await runCliEntry(args)).toBe(1);
  expect(runtime.store.countHumans()).toBe(beforeJoin);
  expect(errors.join("\n")).not.toContain("stale-secret-token");
  vi.stubEnv("CAMPFIRE_TOKEN", "");
  const originalFetch = fetch; let dropped = false;
  vi.stubGlobal("fetch", async (...args: Parameters<typeof fetch>) => {
    const response = await originalFetch(...args);
    if (String(args[0]).endsWith("/v1/enrollment/redeem") && !dropped) { dropped = true; throw new Error("lost response"); }
    return response;
  });
  expect(await runCliEntry(args)).toBe(1);
  expect(loadAnyProfile()?.humanId).toBe("hum_old");
  const joinedDir = join(root, "profiles", readdirSync(join(root, "profiles"))[0]!);
  const pendingPath = join(joinedDir, "pending-enrollment.json");
  const legacyPending = JSON.parse(readFileSync(pendingPath, "utf8")); delete legacyPending.opencodeMajor;
  writeFileSync(pendingPath, JSON.stringify(legacyPending));
  const count = runtime.store.countHumans();
  expect(await runCliEntry(args)).toBe(0);
  expect(runtime.store.countHumans()).toBe(count);
  const result = JSON.parse(output.at(-1) ?? "{}") as { profileId: string; connectionNames: { opencode: string } };
  expect(result.profileId).toMatch(/^join-ein_/);
  expect(result.connectionNames.opencode).toMatch(/^campfire_/);
  const data = parseJsonc(readFileSync(configPath, "utf8")) as any;
  const servers = major === 2 ? data.mcp.servers : data.mcp;
  expect(servers.campfire).toEqual(oldServer);
  expect(servers[result.connectionNames.opencode].environment.CAMPFIRE_TOKEN).toBeUndefined();
  expect(servers[result.connectionNames.opencode].environment.CAMPFIRE_MCP_PROFILE_DIR).toBe(resolveProfilePaths().configDir);
  const agentToken = loadCredentials()!.agents!.opencode!;
  const identity = await campfireHttpCall<{ actor: { actorId: string; actorType: string } }>({ baseUrl: server.url, token: agentToken, method: "whoami" });
  expect(identity.actor.actorType).toBe("agent");
  const context = await campfireHttpCall<{ workspace: { id: string } }>({ baseUrl: server.url, token: agentToken, method: "get_workspace_context", params: { workspaceId: FIXTURE.workspaces.billing } });
  expect(context.workspace.id).toBe(FIXTURE.workspaces.billing);
  expect(loadAnyProfile()).toMatchObject({ mode: "remote", humanName: "Sammi", workspaceId: FIXTURE.workspaces.billing });
  expect(readFileSync(join(root, "config.json"), "utf8")).toBe(oldProfile);
  expect(readFileSync(join(root, "credentials.json"), "utf8")).toBe(oldCredentials);
  expect(await runCliEntry(["status", "--output", "json"])).toBe(0);
  expect(await runCliEntry(["connect", "--harness", "opencode", "--output", "json"])).toBe(0);
  const reconnected = parseJsonc(readFileSync(configPath, "utf8")) as any;
  expect((major === 2 ? reconnected.mcp.servers : reconnected.mcp).campfire).toEqual(oldServer);
  const receiptPath = join(joinedDir, "enrollment-receipt.json");
  const legacyReceipt = JSON.parse(readFileSync(receiptPath, "utf8")); delete legacyReceipt.opencodeMajor;
  writeFileSync(receiptPath, JSON.stringify(legacyReceipt));
  expect(await runCliEntry(args)).toBe(0); // Legacy completed-link retry detects the installed harness.
  expect(runtime.store.countHumans()).toBe(count);
  expect(await runCliEntry(["profiles", "use", "default"])).toBe(0);
  expect(loadAnyProfile()?.humanId).toBe("hum_old");
  expect(await runCliEntry(["profiles", "use", result.profileId])).toBe(0);
  expect(loadAnyProfile()?.humanName).toBe("Sammi");
  // Another invitation to the same workspace represents another identity;
  // its connection must not overwrite or collide with the first one.
  const issued = await campfireHttpCall<IssuedEnrollmentInvitation>({ baseUrl: server.url, token: FIXTURE.tokens.sergio, method: "issue_enrollment_invitation", params: { workspaceId: FIXTURE.workspaces.billing } });
  const secondLink = formatInvitationLink(server.url, issued, true);
  const nextArgs = ["join", "--invitation-link", secondLink, "--accept", "--human-name", "Sammi Second", "--harness", "opencode", "--allow-loopback", "--output", "json"];
  expect(await runCliEntry(nextArgs)).toBe(0);
  const second = JSON.parse(output.at(-1) ?? "{}") as { profileId: string; connectionNames: { opencode: string } };
  expect(second.connectionNames.opencode).not.toBe(result.connectionNames.opencode);
  const both = parseJsonc(readFileSync(configPath, "utf8")) as any;
  const bothServers = major === 2 ? both.mcp.servers : both.mcp;
  expect(bothServers.campfire).toEqual(oldServer);
  expect(bothServers[result.connectionNames.opencode].environment.CAMPFIRE_MCP_PROFILE_DIR).not.toBe(bothServers[second.connectionNames.opencode].environment.CAMPFIRE_MCP_PROFILE_DIR);
  expect(bothServers[second.connectionNames.opencode].environment.CAMPFIRE_TOKEN).toBeUndefined();
  expect(await runCliEntry(["profiles", "use", result.profileId])).toBe(0);
  expect(loadAnyProfile()?.humanName).toBe("Sammi");
  expect(existsSync(resolveProfilePaths().defaultDatabasePath)).toBe(false);
  expect(errors.join("\n")).not.toContain("old-agent-token");
});

it("keeps the joined connection when the original profile connects for the first time", async () => {
  const dir = mkdtempSync(join(tmpdir(), "campfire-no-old-connection-"));
  const runtime = createRuntimeFromPath(join(dir, "owner.db")); seedFixture(runtime.store);
  const server = await startCampfireHttpServer({ runtime, port: 0 });
  cleanup.push(() => rmSync(dir, { recursive: true, force: true }), () => runtime.close(), () => server.close());
  const root = join(dir, "profile"), xdg = join(dir, "xdg"), bin = join(dir, "bin");
  mkdirSync(root, { recursive: true, mode: 0o700 }); mkdirSync(bin, { recursive: true });
  const executable = join(bin, "opencode"); writeFileSync(executable, "#!/bin/sh\nif [ \"$1\" = \"--version\" ]; then printf '1.3.0\\n'; elif [ -f \"$XDG_CONFIG_HOME/opencode/opencode.json\" ]; then cat \"$XDG_CONFIG_HOME/opencode/opencode.json\"; else printf '{}'; fi\n"); chmodSync(executable, 0o755);
  vi.stubEnv("PATH", `${bin}${delimiter}${process.env.PATH ?? ""}`); vi.stubEnv("HOME", join(dir, "home"));
  vi.stubEnv("XDG_CONFIG_HOME", xdg); vi.stubEnv("CAMPFIRE_CONFIG_DIR", root); vi.stubEnv("CAMPFIRE_DATA_DIR", join(dir, "data"));
  for (const key of ["CAMPFIRE_URL", "CAMPFIRE_TOKEN", "CAMPFIRE_ACTOR_ID", "CAMPFIRE_ACTOR_TYPE", "CAMPFIRE_SESSION_ID", "CAMPFIRE_HARNESS"]) vi.stubEnv(key, "");
  writeFileSync(join(root, "config.json"), JSON.stringify({ version: 1, databasePath: join(dir, "owner.db"), url: server.url, humanId: FIXTURE.humans.alice, humanName: "Alice", workspaceId: FIXTURE.workspaces.billing }));
  writeFileSync(join(root, "credentials.json"), JSON.stringify({ humanToken: FIXTURE.tokens.alice }), { mode: 0o600 });
  const issued = await campfireHttpCall<IssuedEnrollmentInvitation>({ baseUrl: server.url, token: FIXTURE.tokens.sergio, method: "issue_enrollment_invitation", params: { workspaceId: FIXTURE.workspaces.billing } });
  const link = formatInvitationLink(server.url, issued, true);
  const output: string[] = []; vi.spyOn(console, "log").mockImplementation((value) => output.push(String(value))); vi.spyOn(console, "error").mockImplementation(() => {});
  expect(await runCliEntry(["join", "--invitation-link", link, "--accept", "--human-name", "Sammi", "--harness", "opencode", "--allow-loopback", "--output", "json"])).toBe(0);
  const joined = JSON.parse(output.at(-1) ?? "{}") as { profileId: string; connectionNames: { opencode: string } };
  expect(joined.connectionNames.opencode).toMatch(/^campfire_/);
  const configPath = join(xdg, "opencode", "opencode.json");
  const before = parseJsonc(readFileSync(configPath, "utf8")) as any;
  const joinedDir = before.mcp[joined.connectionNames.opencode].environment.CAMPFIRE_MCP_PROFILE_DIR;
  expect(before.mcp[joined.connectionNames.opencode].environment.CAMPFIRE_TOKEN).toBeUndefined();
  expect(await runCliEntry(["profiles", "use", "default"])).toBe(0);
  expect(await runCliEntry(["connect", "--harness", "opencode", "--config", configPath, "--token", FIXTURE.tokens.opencodeAlice, "--output", "json"])).toBe(0);
  const after = parseJsonc(readFileSync(configPath, "utf8")) as any;
  expect(after.mcp.campfire.environment.CAMPFIRE_TOKEN).toBe(FIXTURE.tokens.opencodeAlice);
  expect(after.mcp[joined.connectionNames.opencode].environment.CAMPFIRE_MCP_PROFILE_DIR).toBe(joinedDir);
  expect(await runCliEntry(["profiles", "use", joined.profileId])).toBe(0);
  expect(loadAnyProfile()?.humanName).toBe("Sammi");
});
